"""
W2-QI2 — Message schedule as a stabilizer code -> trail weight = code distance.

Card claim: schedule parities = stabilizer generators; minimal trail weight = code
distance d(C); neutral moves = logical operators; carry = non-stabilizer perturbation.
Probe (N=4..12): build the GF(2) check matrix H for the first r rounds; low-weight-
codeword search for d(r); does d(r) JUMP near round 59? does the logical-operator count
track 256-132? **report the carry-gap (trail weight - d(C)), not just d(C)**.
Kill: dead if d(r) grows smoothly with NO jump near 59 and the logical count shows no
link to 132/256.

Construction (faithful to the card): the XOR-linearized SHA-256 message schedule
  W[i] = sigma1(W[i-2]) ^ W[i-7] ^ sigma0(W[i-15]) ^ W[i-16],  sigma GF(2)-linear,
is a linear recurrence. The code C(r) = { full schedule-difference vector [W[0..r-1]] :
the recurrence holds } is generated by the 16N free seed bits W[0..15]. We build its
generator matrix G(r) (each output schedule bit as a GF(2) linear function of the 16N
seed bits) and find d(r) = min nonzero codeword weight by information-set decoding
(Lee-Brickell, small p) -- exact-ish at the small N we use, with brute fallback.

The "carry-gap" = (true differential trail weight) - d(C): we estimate the true trail
weight as the minimum HAMMING weight of the MODULAR-add schedule difference realizing
the same seed difference (carries restored), minus the linear d(C). If the schedule were
purely linear the gap is 0; carries can only ADD weight, so gap>=0, and the card's
non-rebrand claim is gap = the QI1 magic budget.
"""
